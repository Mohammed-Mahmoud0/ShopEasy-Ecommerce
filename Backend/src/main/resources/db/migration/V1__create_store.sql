CREATE TABLE ${flyway:defaultSchema}.app_users (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email varchar(255) NOT NULL UNIQUE,
    password_hash varchar(255) NOT NULL,
    name varchar(100) NOT NULL,
    role varchar(20) NOT NULL
);

CREATE TABLE ${flyway:defaultSchema}.products (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name varchar(150) NOT NULL,
    description varchar(2000) NOT NULL,
    brand varchar(100) NOT NULL,
    price numeric(12, 2) NOT NULL CHECK (price >= 0),
    category varchar(100) NOT NULL,
    stock_quantity integer NOT NULL CHECK (stock_quantity >= 0),
    active boolean NOT NULL DEFAULT true
);

CREATE TABLE ${flyway:defaultSchema}.product_images (
    product_id bigint PRIMARY KEY REFERENCES ${flyway:defaultSchema}.products(id),
    content_type varchar(50) NOT NULL,
    data bytea NOT NULL
);

CREATE TABLE ${flyway:defaultSchema}.cart_items (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id bigint NOT NULL REFERENCES ${flyway:defaultSchema}.app_users(id),
    product_id bigint NOT NULL REFERENCES ${flyway:defaultSchema}.products(id),
    quantity integer NOT NULL CHECK (quantity > 0),
    UNIQUE (user_id, product_id)
);

CREATE TABLE ${flyway:defaultSchema}.orders (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    public_id varchar(36) NOT NULL UNIQUE,
    user_id bigint NOT NULL REFERENCES ${flyway:defaultSchema}.app_users(id),
    status varchar(20) NOT NULL,
    created_at timestamp(6) with time zone NOT NULL,
    total numeric(12, 2) NOT NULL CHECK (total >= 0)
);

CREATE TABLE ${flyway:defaultSchema}.order_items (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id bigint NOT NULL REFERENCES ${flyway:defaultSchema}.orders(id),
    product_id bigint NOT NULL REFERENCES ${flyway:defaultSchema}.products(id),
    product_name varchar(150) NOT NULL,
    unit_price numeric(12, 2) NOT NULL,
    quantity integer NOT NULL CHECK (quantity > 0),
    line_total numeric(12, 2) NOT NULL
);

CREATE INDEX ix_orders_user_id ON ${flyway:defaultSchema}.orders(user_id);
CREATE INDEX ix_cart_items_user_id ON ${flyway:defaultSchema}.cart_items(user_id);
CREATE INDEX ix_products_category ON ${flyway:defaultSchema}.products(category);
